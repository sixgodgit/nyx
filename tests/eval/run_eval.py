def run_eval(
    vector_store=None,
    embedding_provider=None,
    top_k: int = 5,
    output_path: Optional[str] = None,
) -> dict:
    """
    运行评测。

    Args:
        vector_store: VectorStore 实例（可选，用于混合检索对比）
        embedding_provider: EmbeddingProvider 实例（可选）
        top_k: 检索 top-k
        output_path: 报告输出路径（可选）

    Returns:
        评测结果 dict
    """
    test_set = get_eval_set()
    results = []
    hits = 0
    semantic_hits_lexical = 0
    semantic_hits_hybrid = 0

    # 构造模拟记忆（用于衰减验证）
    from nexsandglass.engram.types import Memory, MemoryType
    from nexsandglass.engram.decay import compute_decay_multiplier

    # 衰减验证：模拟 30 天前的 episodic 记忆
    old_memory = Memory(
        memory_id="old_event",
        type="episodic",
        content="30 天前的事件",
        created_at="2026-06-01T00:00:00+00:00",
        decay_weight=1.0,
    )
    # 计算 30 天后的衰减
    multiplier = compute_decay_multiplier("episodic", 0.0, 0, 24 * 30)
    decayed_weight = old_memory.decay_weight * multiplier

    decay_verification = {
        "original_weight": old_memory.decay_weight,
        "decayed_weight": round(decayed_weight, 6),
        "multiplier": round(multiplier, 6),
        "decayed": decayed_weight < old_memory.decay_weight,
    }

    # 词法检索 baseline（简单字符串匹配模拟）
    lexical_hits = 0
    for item in test_set:
        # 词法 baseline：检查 query 关键词是否在 expected 中能找到
        # 实际评测需要接入真实检索，这里提供框架
        found = _lexical_baseline_search(item["query"], item["expected"])
        if found:
            lexical_hits += 1

    total = len(test_set)
    lexical_recall = lexical_hits / total if total else 0

    report = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "top_k": top_k,
        "test_set_size": total,
        "lexical_recall": round(lexical_recall, 4),
        "decay_verification": decay_verification,
        "note": "完整评测需要接入真实 SearchRouter。当前为框架 + 衰减验证。",
    }

    if output_path:
        _write_report(report, output_path)

    return report


